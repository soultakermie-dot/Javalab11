-- Створення бази даних
CREATE DATABASE IF NOT EXISTS company_db;
USE company_db;

-- Створення таблиці Відділи (Departments)
CREATE TABLE IF NOT EXISTS Відділи (
    Номер_відділу INT PRIMARY KEY,
    Назва CHAR(30) NOT NULL,
    Телефон CHAR(15)
);

-- Створення таблиці Співробітники (Employees)
CREATE TABLE IF NOT EXISTS Співробітники (
    Номер_співробітника INT PRIMARY KEY,
    Прізвище VARCHAR(20) NOT NULL,
    Ім_я VARCHAR(10) NOT NULL,
    Посада VARCHAR(20),
    Номер_відділу INT,
    FOREIGN KEY (Номер_відділу) REFERENCES Відділи(Номер_відділу)
        ON DELETE SET NULL
        ON UPDATE CASCADE
);

-- Створення таблиці Завдання (Tasks)
CREATE TABLE IF NOT EXISTS Завдання (
    Номер_завдання INT PRIMARY KEY AUTO_INCREMENT,
    Опис_завдання VARCHAR(50) NOT NULL,
    Номер_співробітника INT,
    FOREIGN KEY (Номер_співробітника) REFERENCES Співробітники(Номер_співробітника)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

